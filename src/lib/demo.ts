import type { ContentType, Tone } from "./types";

const toneFlavor: Record<Tone, string> = {
  professional: "уверенный деловой тон, без воды",
  friendly: "тёплый и открытый тон, как разговор с коллегой",
  bold: "смелые формулировки и акцент на измеримый результат",
  witty: "лёгкая острота без панибратства",
  concise: "максимально плотный текст, только суть",
};

export function buildDemoResult(
  type: ContentType,
  tone: Tone,
  topic: string,
  audience?: string,
  extra?: string,
): string {
  const who = audience?.trim() || "целевой аудитории";
  const note = extra?.trim() ? `\n\nДополнительно учтено: ${extra.trim()}` : "";
  const flavor = toneFlavor[tone];

  if (type === "post") {
    return `Демо-режим (без API-ключа) · тон: ${flavor}

${topic}

За последние месяцы я много думал про это — и вот к чему пришёл.

1. Начинайте с проблемы, а не с решения.
2. Показывайте процесс, а не только итог.
3. Делитесь одним конкретным инсайтом, который можно применить уже сегодня.

Если вы из круга ${who} — напишите в комментариях, что сработало у вас. Обменяемся опытом.

#growth #career #learning${note}

— Sparkwrit demo`;
  }

  if (type === "resume") {
    return `Демо-режим (без API-ключа) · тон: ${flavor}

PROFESSIONAL SUMMARY
Специалист с фокусом на «${topic}». Умею превращать сложные задачи в понятные результаты для ${who}.

KEY HIGHLIGHTS
• Сформулировал и довёл до релиза инициативу вокруг «${topic}»
• Сократил время рутинных процессов за счёт ясной приоритизации
• Выстроил коммуникацию между стейкхолдерами без потери качества

SELECTED EXPERIENCE
Role · Company
— Вёл проекты по направлению «${topic}», от гипотезы до измеримого эффекта
— Документировал решения так, чтобы ими могли пользоваться другие команды${note}

— Sparkwrit demo`;
  }

  return `Демо-режим (без API-ключа) · тон: ${flavor}

Здравствуйте!

Меня заинтересовала возможность присоединиться к вашей команде. Тема «${topic}» — именно то, чем я живу в работе: доводить идеи до понятного результата для ${who}.

В прошлых проектах я:
• быстро разбирался в контексте и предлагал рабочий план;
• держал фокус на ценности для пользователя, а не на «галочках»;
• спокойно закрывал edge cases и коммуникацию со стейкхолдерами.

Буду рад обсудить, как мой опыт может усилить вашу команду.

С уважением,
[Ваше Имя]${note}

— Sparkwrit demo`;
}

export function buildSystemPrompt(type: ContentType, tone: Tone): string {
  const typeMap: Record<ContentType, string> = {
    post: "социальный пост (LinkedIn / X / Telegram)",
    resume: "блок резюме (summary + highlights)",
    cover: "сопроводительное письмо",
  };

  return `Ты — опытный карьерный копирайтер. Пиши на русском языке.
Создай ${typeMap[type]} в тоне: ${toneFlavor[tone]}.
Не используй markdown-заголовки ##. Можно списки и короткие абзацы.
Без извинений и мета-комментариев. Верни только готовый текст.`;
}
